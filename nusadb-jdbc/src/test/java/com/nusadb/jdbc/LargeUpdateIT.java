package com.nusadb.jdbc;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.nusadb.testing.NusaTestServer;
import java.sql.BatchUpdateException;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import org.junit.jupiter.api.Test;

/** executeLargeUpdate, executeLargeBatch, getLargeUpdateCount and setLargeMaxRows. */
class LargeUpdateIT {

    private static void table(Connection c) throws SQLException {
        try (Statement st = c.createStatement()) {
            st.execute("CREATE TABLE IF NOT EXISTS large_it (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v int)");
            st.execute("DELETE FROM large_it");
        }
    }

    @Test
    void largeMaxRowsLimitsTheRows() throws SQLException {
        try (Connection c = NusaTestServer.get().connect(); Statement st = c.createStatement()) {
            st.setLargeMaxRows(3);
            assertEquals(3L, st.getLargeMaxRows());
            assertEquals(3, st.getMaxRows());
            int n = 0;
            try (ResultSet rs = st.executeQuery("SELECT g FROM generate_series(1, 10) AS g")) {
                while (rs.next()) {
                    n++;
                }
            }
            assertEquals(3, n);
            st.setLargeMaxRows(Long.MAX_VALUE);
            assertEquals(Integer.MAX_VALUE, st.getMaxRows());
            assertThrows(SQLException.class, () -> st.setLargeMaxRows(-1));
        }
    }

    @Test
    void largeUpdateWithKeysByColumnIndex() throws SQLException {
        try (Connection c = NusaTestServer.get().connect(); Statement st = c.createStatement()) {
            table(c);
            assertEquals(2L, st.executeLargeUpdate("INSERT INTO large_it (v) VALUES (1), (2)", new int[] {1}));
            try (ResultSet keys = st.getGeneratedKeys()) {
                assertTrue(keys.next());
                assertTrue(keys.getLong(1) > 0);
            }
        }
    }

    @Test
    void rewrittenLargeBatchReportsNoInfo() throws SQLException {
        try (Connection c = DriverManager.getConnection(NusaTestServer.get().url() + "?rewriteBatchedInserts=true")) {
            table(c);
            try (PreparedStatement ps = c.prepareStatement("INSERT INTO large_it (v) VALUES (?)")) {
                for (int i = 0; i < 3; i++) {
                    ps.setInt(1, i);
                    ps.addBatch();
                }
                long none = Statement.SUCCESS_NO_INFO;
                assertArrayEquals(new long[] {none, none, none}, ps.executeLargeBatch());
            }
        }
    }

    @Test
    void failedBatchCarriesLargeCounts() throws SQLException {
        try (Connection c = NusaTestServer.get().connect(); Statement st = c.createStatement()) {
            table(c);
            st.addBatch("INSERT INTO large_it (id, v) VALUES (1, 1)");
            st.addBatch("INSERT INTO large_it (id, v) VALUES (1, 2)");
            BatchUpdateException e = assertThrows(BatchUpdateException.class, st::executeLargeBatch);
            assertNotNull(e.getLargeUpdateCounts());
            assertArrayEquals(new long[] {1L}, e.getLargeUpdateCounts());
            assertArrayEquals(new int[] {1}, e.getUpdateCounts());
        }
    }

    @Test
    void preparedStatementRefusesSqlArgument() throws SQLException {
        try (Connection c = NusaTestServer.get().connect(); PreparedStatement ps = c.prepareStatement("SELECT 1")) {
            assertThrows(SQLException.class, () -> ps.executeLargeUpdate("DELETE FROM large_it"));
        }
    }

    @Test
    void countsPastIntRangeNarrowToMaxValue() {
        assertEquals(5_000_000_000L, NusaStatement.affected("UPDATE 5000000000"));
        assertEquals(Integer.MAX_VALUE, NusaStatement.narrow(5_000_000_000L));
        assertEquals(-1, NusaStatement.narrow(-1L));
        assertArrayEquals(new int[] {1, Statement.SUCCESS_NO_INFO, Integer.MAX_VALUE},
                NusaStatement.narrow(new long[] {1, Statement.SUCCESS_NO_INFO, 3_000_000_000L}));
    }
}
