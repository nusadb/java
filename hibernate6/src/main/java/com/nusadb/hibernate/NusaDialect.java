/**
 * Hibernate ORM 6.x dialect for NusaDB. A thin layer over the {@code nusadb-jdbc} driver: it maps
 * JDBC type codes to the column types NusaDB accepts in {@code CREATE TABLE} and renders pagination
 * as inline literals (the server requires a constant {@code LIMIT}).
 *
 * <p>Every {@code @GeneratedValue} strategy works: {@code IDENTITY} as a
 * {@code GENERATED BY DEFAULT AS IDENTITY} column, and {@code SEQUENCE} and {@code AUTO} as native
 * sequences (pooled when {@code allocationSize > 1}). Configure it with:
 *
 * <pre>
 * hibernate.dialect = com.nusadb.hibernate.NusaDialect
 * hibernate.connection.driver_class = com.nusadb.jdbc.NusaDriver
 * hibernate.boot.allow_jdbc_metadata_access = false
 * </pre>
 */
public class NusaDialect extends Dialect {

    public NusaDialect() {
        super(DatabaseVersion.make(1, 0));
    }

    @Override
    protected String columnType(int sqlTypeCode) {
        switch (sqlTypeCode) {
            case Types.BOOLEAN:
            case Types.BIT:
                return "boolean";
            case Types.TINYINT:
            case Types.SMALLINT:
                return "smallint";
            case Types.INTEGER:
                return "int";
            case Types.BIGINT:
                return "bigint";
            case Types.REAL:
            case Types.FLOAT:
                return "real";
            case Types.DOUBLE:
                return "double precision";
            case Types.NUMERIC:
            case Types.DECIMAL:
                return "numeric($p,$s)";
            case Types.CHAR:
            case Types.VARCHAR:
            case Types.LONGVARCHAR:
            case Types.NCHAR:
            case Types.NVARCHAR:
            case Types.LONGNVARCHAR:
            case Types.CLOB:
            case Types.NCLOB:
                return "text";
            case Types.DATE:
                return "date";
            case Types.TIME:
            case Types.TIME_WITH_TIMEZONE:
                return "time";
            case Types.TIMESTAMP:
            case Types.TIMESTAMP_WITH_TIMEZONE:
                return "timestamp";
            case Types.BINARY:
            case Types.VARBINARY:
            case Types.LONGVARBINARY:
            case Types.BLOB:
                return "varbinary";
            default:
                return super.columnType(sqlTypeCode);
        }
    }

    @Override
    protected void registerColumnTypes(TypeContributions typeContributions, ServiceRegistry serviceRegistry) {
        super.registerColumnTypes(typeContributions, serviceRegistry);
        typeContributions.getTypeConfiguration().getDdlTypeRegistry()
                .addDescriptor(new DdlTypeImpl(SqlTypes.UUID, "uuid", this));
    }

    @Override
    public void contributeTypes(TypeContributions typeContributions, ServiceRegistry serviceRegistry) {
        super.contributeTypes(typeContributions, serviceRegistry);
        // java.util.UUID as the native UUID type (bound with setObject), not as 16 raw bytes.
        typeContributions.getTypeConfiguration().getJdbcTypeRegistry().addDescriptor(UUIDJdbcType.INSTANCE);
    }

    @Override
    public int getPreferredSqlTypeCodeForBoolean() {
        return Types.BOOLEAN;
    }

    // NusaDB has a real BOOLEAN: comparing it with 1/0 (the generic rendering) is a type error.

    @Override
    public String toBooleanValueString(boolean bool) {
        return bool ? "true" : "false";
    }

    @Override
    public void appendBooleanValueString(SqlAppender appender, boolean bool) {
        appender.appendSql(toBooleanValueString(bool));
    }

    // ---- HQL functions -------------------------------------------------------------------------

    @Override
    public void initializeFunctionRegistry(FunctionContributions functionContributions) {
        super.initializeFunctionRegistry(functionContributions);
        CommonFunctionFactory functions = new CommonFunctionFactory(functionContributions);
        // locate() and position(): the server has position(x in y) but no locate().
        functions.locate_positionSubstring();
        // trunc()/truncate() of a number with trunc(), of a datetime with date_trunc().
        functions.trunc_dateTrunc();
        functions.dateTrunc();
        // listagg(x, sep) within group (order by ..) as string_agg(x, sep order by ..).
        functions.listagg_stringAgg("varchar");
    }

    @Override
    public String trimPattern(TrimSpec specification, boolean isWhitespace) {
        // The server needs the character to trim: trim(both ' ' from x), not trim(both from x).
        return "trim(" + specification.name().toLowerCase(Locale.ROOT) + (isWhitespace ? " ' '" : " ?2") + " from ?1)";
    }

    @Override
    public String translateExtractField(TemporalUnit unit) {
        switch (unit) {
            case DAY_OF_MONTH:
                return "day";
            case DAY_OF_YEAR:
                return "doy";
            case DAY_OF_WEEK:
                return "dow";
            default:
                return super.translateExtractField(unit);
        }
    }

    @Override
    public String extractPattern(TemporalUnit unit) {
        // dow counts Sunday as 0; HQL's day of week counts it as 1.
        return unit == TemporalUnit.DAY_OF_WEEK ? "(extract(dow from ?2)+1)" : super.extractPattern(unit);
    }

    @Override
    public long getFractionalSecondPrecisionInNanos() {
        return 1_000; // timestamps keep microseconds
    }

    @Override
    public String timestampaddPattern(TemporalUnit unit, TemporalType temporalType, IntervalType intervalType) {
        if (intervalType != null) {
            return "(?2+?3)";
        }
        String interval;
        switch (unit) {
            case NANOSECOND:
                return "(?3+(?2)/1e3*interval '1 microsecond')";
            case NATIVE:
                return "(?3+(?2)*interval '1 microsecond')";
            case HOUR:
            case MINUTE:
            case SECOND:
                return "(?3+(?2)*interval '1 " + unit.name().toLowerCase(Locale.ROOT) + "')";
            case QUARTER:
                interval = "3 month";
                break;
            case YEAR:
            case MONTH:
            case WEEK:
            case DAY:
                interval = "1 " + unit.name().toLowerCase(Locale.ROOT);
                break;
            default:
                return super.timestampaddPattern(unit, temporalType, intervalType);
        }
        String sum = "(?3+(?2)*interval '" + interval + "')";
        // date + interval is a timestamp: a date plus whole days, weeks, months stays a date.
        return temporalType == TemporalType.DATE ? "cast(" + sum + " as date)" : sum;
    }

    @Override
    public String timestampdiffPattern(TemporalUnit unit, TemporalType fromTemporalType, TemporalType toTemporalType) {
        if (unit == null) {
            return "(?3-?2)";
        }
        String months = "(extract(year from age(?3,?2))*12+extract(month from age(?3,?2)))";
        switch (unit) {
            case YEAR:
                return "extract(year from age(?3,?2))";
            case QUARTER:
                return "trunc(" + months + "/3)";
            case MONTH:
                return months;
            default:
                break;
        }
        if (fromTemporalType == TemporalType.DATE && toTemporalType == TemporalType.DATE) {
            // date - date is a whole number of days.
            switch (unit) {
                case WEEK:
                    return "((?3-?2)/7)";
                case DAY:
                    return "(?3-?2)";
                case HOUR:
                    return "((?3-?2)*24)";
                case MINUTE:
                    return "((?3-?2)*1440)";
                case SECOND:
                    return "((?3-?2)*86400)";
                case NATIVE:
                    return "((?3-?2)*86400000000)";
                case NANOSECOND:
                    return "((?3-?2)*86400000000000)";
                default:
                    return super.timestampdiffPattern(unit, fromTemporalType, toTemporalType);
            }
        }
        // timestamp - timestamp is an interval of days and time.
        switch (unit) {
            case WEEK:
                return "trunc(extract(day from ?3-?2)/7)";
            case DAY:
                return "extract(day from ?3-?2)";
            case HOUR:
                return "trunc(extract(epoch from ?3-?2)/3600)";
            case MINUTE:
                return "trunc(extract(epoch from ?3-?2)/60)";
            case SECOND:
                return "trunc(extract(epoch from ?3-?2))";
            case NATIVE:
                return "trunc(extract(epoch from ?3-?2)*1000000)";
            case NANOSECOND:
                return "trunc(extract(epoch from ?3-?2)*1000000000)";
            default:
                return super.timestampdiffPattern(unit, fromTemporalType, toTemporalType);
        }
    }

    @Override
    public String currentLocalTime() {
        return "cast(localtimestamp as time)"; // the server has no LOCALTIME
    }

    // Datetime literals as typed SQL literals (date '..'), not the JDBC escapes ({d '..'}) the
    // server does not parse.

    @Override
    public void appendDateTimeLiteral(SqlAppender appender, TemporalAccessor temporalAccessor, TemporalType precision,
            TimeZone jdbcTimeZone) {
        boolean offset = temporalAccessor.isSupported(ChronoField.OFFSET_SECONDS);
        switch (precision) {
            case DATE:
                appender.appendSql("date '");
                DateTimeUtils.appendAsDate(appender, temporalAccessor);
                break;
            case TIME:
                appender.appendSql("time '");
                DateTimeUtils.appendAsLocalTime(appender, temporalAccessor);
                break;
            case TIMESTAMP:
                appender.appendSql(offset ? "timestamp with time zone '" : "timestamp '");
                DateTimeUtils.appendAsTimestampWithMicros(appender, temporalAccessor, offset, jdbcTimeZone);
                break;
            default:
                throw new IllegalArgumentException();
        }
        appender.appendSql('\'');
    }

    @Override
    public void appendDateTimeLiteral(SqlAppender appender, Date date, TemporalType precision, TimeZone jdbcTimeZone) {
        switch (precision) {
            case DATE:
                appender.appendSql("date '");
                DateTimeUtils.appendAsDate(appender, date);
                break;
            case TIME:
                appender.appendSql("time '");
                DateTimeUtils.appendAsLocalTime(appender, date);
                break;
            case TIMESTAMP:
                appender.appendSql("timestamp '");
                DateTimeUtils.appendAsTimestampWithMicros(appender, date, jdbcTimeZone);
                break;
            default:
                throw new IllegalArgumentException();
        }
        appender.appendSql('\'');
    }

    @Override
    public void appendDateTimeLiteral(SqlAppender appender, Calendar calendar, TemporalType precision,
            TimeZone jdbcTimeZone) {
        switch (precision) {
            case DATE:
                appender.appendSql("date '");
                DateTimeUtils.appendAsDate(appender, calendar);
                break;
            case TIME:
                appender.appendSql("time '");
                DateTimeUtils.appendAsLocalTime(appender, calendar);
                break;
            case TIMESTAMP:
                appender.appendSql("timestamp '");
                DateTimeUtils.appendAsTimestampWithMicros(appender, calendar, jdbcTimeZone);
                break;
            default:
                throw new IllegalArgumentException();
        }
        appender.appendSql('\'');
    }

    @Override
    public LimitHandler getLimitHandler() {
        return NusaLimitHandler.INSTANCE;
    }

    @Override
    public boolean supportsFetchClause(FetchClauseType type) {
        // NusaDB has no ANSI 'OFFSET .. FETCH' clause; pagination is rendered as a constant
        // 'LIMIT'/'OFFSET' by NusaSqlAstTranslator (the server rejects a parameterised row count).
        return false;
    }

    @Override
    public SqlAstTranslatorFactory getSqlAstTranslatorFactory() {
        return new StandardSqlAstTranslatorFactory() {
            @Override
            protected <T extends JdbcOperation> SqlAstTranslator<T> buildTranslator(
                    SessionFactoryImplementor sessionFactory, Statement statement) {
                return new NusaSqlAstTranslator<>(sessionFactory, statement);
            }
        };
    }

    @Override
    public IdentityColumnSupport getIdentityColumnSupport() {
        return NusaIdentityColumnSupport.INSTANCE;
    }

    @Override
    public boolean supportsInsertReturningGeneratedKeys() {
        // getGeneratedKeys() with the key column names: the driver appends RETURNING <columns>.
        return true;
    }

    // Schema drops (create, create-drop) name tables and constraints that may not exist yet, as on a
    // fresh database: "drop table if exists t cascade", "alter table if exists t drop constraint if exists c".

    @Override
    public boolean supportsIfExistsBeforeTableName() {
        return true;
    }

    @Override
    public boolean supportsIfExistsAfterAlterTable() {
        return true;
    }

    @Override
    public boolean supportsIfExistsBeforeConstraintName() {
        return true;
    }

    @Override
    public String getCascadeConstraintsString() {
        return " cascade";
    }

    @Override
    public ViolatedConstraintNameExtractor getViolatedConstraintNameExtractor() {
        return NusaConstraintNames::of;
    }

    @Override
    public SequenceSupport getSequenceSupport() {
        return NusaSequenceSupport.INSTANCE;
    }

    @Override
    public String getQuerySequencesString() {
        return "select * from information_schema.sequences";
    }

    @Override
    public SequenceInformationExtractor getSequenceInformationExtractor() {
        // Reads the standard information_schema.sequences columns (sequence_name, start_value,
        // minimum_value, maximum_value, increment), which the server provides.
        return SequenceInformationExtractorLegacyImpl.INSTANCE;
    }
}
