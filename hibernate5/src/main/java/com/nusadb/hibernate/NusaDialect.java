/**
 * Hibernate ORM 5.6 dialect for NusaDB. A thin layer over the {@code nusadb-jdbc} driver: it maps
 * JDBC type codes to the column types NusaDB accepts in {@code CREATE TABLE}, registers the HQL
 * functions under the names the server has, and renders pagination as inline literals (the server
 * requires a constant {@code LIMIT}).
 *
 * <p>Every {@code @GeneratedValue} strategy works: {@code IDENTITY} as a
 * {@code GENERATED BY DEFAULT AS IDENTITY} column, and {@code SEQUENCE} and {@code AUTO} as native
 * sequences (pooled when {@code allocationSize > 1}). {@code java.util.UUID} is stored in a
 * {@code uuid} column. Configure it with:
 *
 * <pre>
 * hibernate.dialect = com.nusadb.hibernate.NusaDialect
 * hibernate.connection.driver_class = com.nusadb.jdbc.NusaDriver
 * </pre>
 */
public class NusaDialect extends Dialect {

    public NusaDialect() {
        super();
        registerColumnType(Types.BOOLEAN, "boolean");
        registerColumnType(Types.BIT, "boolean");
        registerColumnType(Types.TINYINT, "smallint");
        registerColumnType(Types.SMALLINT, "smallint");
        registerColumnType(Types.INTEGER, "int");
        registerColumnType(Types.BIGINT, "bigint");
        registerColumnType(Types.REAL, "real");
        registerColumnType(Types.FLOAT, "real");
        registerColumnType(Types.DOUBLE, "double precision");
        registerColumnType(Types.NUMERIC, "numeric($p,$s)");
        registerColumnType(Types.DECIMAL, "numeric($p,$s)");
        registerColumnType(Types.CHAR, "text");
        registerColumnType(Types.VARCHAR, "text");
        registerColumnType(Types.LONGVARCHAR, "text");
        registerColumnType(Types.NCHAR, "text");
        registerColumnType(Types.NVARCHAR, "text");
        registerColumnType(Types.LONGNVARCHAR, "text");
        registerColumnType(Types.CLOB, "text");
        registerColumnType(Types.NCLOB, "text");
        registerColumnType(Types.DATE, "date");
        registerColumnType(Types.TIME, "time");
        registerColumnType(Types.TIME_WITH_TIMEZONE, "time");
        registerColumnType(Types.TIMESTAMP, "timestamp");
        registerColumnType(Types.TIMESTAMP_WITH_TIMEZONE, "timestamp");
        registerColumnType(Types.BINARY, "varbinary");
        registerColumnType(Types.VARBINARY, "varbinary");
        registerColumnType(Types.LONGVARBINARY, "varbinary");
        registerColumnType(Types.BLOB, "varbinary");
        registerColumnType(Types.OTHER, "uuid");
        registerFunctions();
    }

    // ---- HQL functions -------------------------------------------------------------------------

    private void registerFunctions() {
        // locate(): the server has position(x in y), not locate().
        registerFunction("locate", new NusaLocateFunction());
        registerFunction("str", new SQLFunctionTemplate(StandardBasicTypes.STRING, "cast(?1 as text)"));
        // trim(x) needs the character to trim on the server: trim(both ' ' from x).
        registerFunction("trim", new NusaTrimFunction());

        registerFunction("current_date", new NoArgSQLFunction("current_date", StandardBasicTypes.DATE, false));
        registerFunction("current_time", new NoArgSQLFunction("current_time", StandardBasicTypes.TIME, false));
        registerFunction("current_timestamp", new NoArgSQLFunction("current_timestamp", StandardBasicTypes.TIMESTAMP, false));
        registerFunction("localtimestamp", new NoArgSQLFunction("localtimestamp", StandardBasicTypes.TIMESTAMP, false));
        registerFunction("now", new NoArgSQLFunction("now", StandardBasicTypes.TIMESTAMP));
        registerFunction("date_trunc", new StandardSQLFunction("date_trunc", StandardBasicTypes.TIMESTAMP));
        registerFunction("age", new StandardSQLFunction("age"));

        registerFunction("concat", new VarArgsSQLFunction(StandardBasicTypes.STRING, "(", "||", ")"));
        registerFunction("char_length", new StandardSQLFunction("char_length", StandardBasicTypes.INTEGER));
        registerFunction("lpad", new StandardSQLFunction("lpad", StandardBasicTypes.STRING));
        registerFunction("rpad", new StandardSQLFunction("rpad", StandardBasicTypes.STRING));
        registerFunction("ltrim", new StandardSQLFunction("ltrim", StandardBasicTypes.STRING));
        registerFunction("rtrim", new StandardSQLFunction("rtrim", StandardBasicTypes.STRING));
        registerFunction("left", new StandardSQLFunction("left", StandardBasicTypes.STRING));
        registerFunction("right", new StandardSQLFunction("right", StandardBasicTypes.STRING));
        registerFunction("replace", new StandardSQLFunction("replace", StandardBasicTypes.STRING));
        registerFunction("repeat", new StandardSQLFunction("repeat", StandardBasicTypes.STRING));
        registerFunction("initcap", new StandardSQLFunction("initcap", StandardBasicTypes.STRING));
        registerFunction("md5", new StandardSQLFunction("md5", StandardBasicTypes.STRING));
        registerFunction("ascii", new StandardSQLFunction("ascii", StandardBasicTypes.INTEGER));
        registerFunction("chr", new StandardSQLFunction("chr", StandardBasicTypes.CHARACTER));
        registerFunction("to_char", new StandardSQLFunction("to_char", StandardBasicTypes.STRING));
        registerFunction("string_agg", new StandardSQLFunction("string_agg", StandardBasicTypes.STRING));

        registerFunction("round", new StandardSQLFunction("round"));
        registerFunction("trunc", new StandardSQLFunction("trunc"));
        registerFunction("ceil", new StandardSQLFunction("ceil"));
        registerFunction("ceiling", new StandardSQLFunction("ceiling"));
        registerFunction("floor", new StandardSQLFunction("floor"));
        registerFunction("sign", new StandardSQLFunction("sign", StandardBasicTypes.INTEGER));
        registerFunction("power", new StandardSQLFunction("power", StandardBasicTypes.DOUBLE));
        registerFunction("exp", new StandardSQLFunction("exp", StandardBasicTypes.DOUBLE));
        registerFunction("ln", new StandardSQLFunction("ln", StandardBasicTypes.DOUBLE));
        registerFunction("log", new StandardSQLFunction("log", StandardBasicTypes.DOUBLE));
        registerFunction("random", new NoArgSQLFunction("random", StandardBasicTypes.DOUBLE));
        registerFunction("greatest", new StandardSQLFunction("greatest"));
        registerFunction("least", new StandardSQLFunction("least"));
    }

    // ---- types ---------------------------------------------------------------------------------

    @Override
    public void contributeTypes(TypeContributions typeContributions, ServiceRegistry serviceRegistry) {
        super.contributeTypes(typeContributions, serviceRegistry);
        // java.util.UUID as the native uuid type (bound with setObject), not as 16 raw bytes.
        typeContributions.contributeType(NusaUuidType.INSTANCE);
    }

    /**
     * A CLOB is a {@code text} value and a BLOB a {@code bytea} value on the server, read and written
     * whole, so they are bound as a string and as bytes.
     */
    @Override
    protected SqlTypeDescriptor getSqlTypeDescriptorOverride(int sqlCode) {
        switch (sqlCode) {
            case Types.CLOB:
            case Types.NCLOB:
                return LongVarcharTypeDescriptor.INSTANCE;
            case Types.BLOB:
                return LongVarbinaryTypeDescriptor.INSTANCE;
            default:
                return super.getSqlTypeDescriptorOverride(sqlCode);
        }
    }

    @Override
    public String toBooleanValueString(boolean bool) {
        // NusaDB has a real BOOLEAN: comparing it with 1/0 (the generic rendering) is a type error.
        return bool ? "true" : "false";
    }

    // ---- names ---------------------------------------------------------------------------------

    /**
     * Unquoted names are stored in lower case, quoted ones as written; names the server reserves
     * (such as a column named {@code key}) are quoted.
     */
    @Override
    public IdentifierHelper buildIdentifierHelper(IdentifierHelperBuilder builder, DatabaseMetaData dbMetaData)
            throws SQLException {
        if (dbMetaData == null) {
            builder.setUnquotedCaseStrategy(IdentifierCaseStrategy.LOWER);
            builder.setQuotedCaseStrategy(IdentifierCaseStrategy.MIXED);
        }
        return new NusaIdentifierHelper(super.buildIdentifierHelper(builder, dbMetaData));
    }

    // ---- ids -----------------------------------------------------------------------------------

    @Override
    public IdentityColumnSupport getIdentityColumnSupport() {
        return NusaIdentityColumnSupport.INSTANCE;
    }

    @Override
    public boolean supportsSequences() {
        return true;
    }

    @Override
    public boolean supportsPooledSequences() {
        return true;
    }

    @Override
    public String getSequenceNextValString(String sequenceName) {
        return "select " + getSelectSequenceNextValString(sequenceName);
    }

    /**
     * The server looks the string up as the stored name, without folding case or reading a schema
     * prefix, so it gets the name an unquoted {@code CREATE SEQUENCE} stores.
     */
    @Override
    public String getSelectSequenceNextValString(String sequenceName) {
        return "nextval('" + storedName(sequenceName) + "')";
    }

    @Override
    protected String getCreateSequenceString(String sequenceName) {
        return "create sequence " + sequenceName;
    }

    @Override
    protected String getDropSequenceString(String sequenceName) {
        return "drop sequence if exists " + sequenceName;
    }

    @Override
    public String getQuerySequencesString() {
        return "select * from information_schema.sequences";
    }

    @Override
    public SequenceInformationExtractor getSequenceInformationExtractor() {
        // The standard information_schema.sequences columns, which the server provides.
        return SequenceInformationExtractorLegacyImpl.INSTANCE;
    }

    /**
     * The name a {@code CREATE SEQUENCE <sequenceName>} stores: the last part of a qualified name,
     * unquoted as written when quoted, lower case otherwise.
     */
    static String storedName(String sequenceName) {
        String name = sequenceName.trim();
        String stored;
        if (name.endsWith("\"")) {
            int open = name.lastIndexOf('"', name.length() - 2);
            stored = name.substring(open + 1, name.length() - 1).replace("\"\"", "\"");
        } else {
            stored = name.substring(name.lastIndexOf('.') + 1).toLowerCase(Locale.ROOT);
        }
        return stored.replace("'", "''");
    }

    // ---- queries and locks ---------------------------------------------------------------------

    @Override
    public LimitHandler getLimitHandler() {
        return NusaLimitHandler.INSTANCE;
    }

    @Override
    public boolean supportsCurrentTimestampSelection() {
        return true;
    }

    @Override
    public boolean isCurrentTimestampSelectStringCallable() {
        return false;
    }

    @Override
    public String getCurrentTimestampSelectString() {
        return "select current_timestamp";
    }

    @Override
    public String getForUpdateNowaitString() {
        return " for update nowait";
    }

    @Override
    public String getForUpdateSkipLockedString() {
        return " for update skip locked";
    }

    @Override
    public boolean supportsSkipLocked() {
        return true;
    }

    /** A lock timeout of 0 is NOWAIT and -2 is SKIP LOCKED; any other waits for the lock. */
    @Override
    public String getWriteLockString(int timeout) {
        if (timeout == 0) {
            return getForUpdateNowaitString();
        }
        if (timeout == -2) {
            return getForUpdateSkipLockedString();
        }
        return getForUpdateString();
    }

    @Override
    public String getReadLockString(int timeout) {
        return getWriteLockString(timeout);
    }

    @Override
    public String getAddColumnString() {
        return "add column";
    }

    @Override
    public boolean supportsUnionAll() {
        return true;
    }

    @Override
    public boolean supportsRowValueConstructorSyntax() {
        return true;
    }

    @Override
    public boolean supportsRowValueConstructorSyntaxInInList() {
        return true;
    }

    // ---- schema --------------------------------------------------------------------------------

    // Schema drops name tables and constraints that may not exist yet, as on a fresh database.

    @Override
    public boolean supportsIfExistsBeforeTableName() {
        return true;
    }

    @Override
    public boolean supportsIfExistsAfterAlterTable() {
        return true;
    }

    @Override
    public boolean supportsIfExistsBeforeConstraintName() {
        return true;
    }

    @Override
    public String getCascadeConstraintsString() {
        return " cascade";
    }

    // ---- errors --------------------------------------------------------------------------------

    @Override
    public ViolatedConstraintNameExtracter getViolatedConstraintNameExtracter() {
        return NusaConstraintNames::of;
    }

    /**
     * Lock and timeout errors as Hibernate's typed exceptions (so Spring reports a
     * {@code PessimisticLockingFailureException} or {@code QueryTimeoutException}); the server uses
     * the standard SQLStates for them.
     */
    @Override
    public SQLExceptionConversionDelegate buildSQLExceptionConversionDelegate() {
        return (sqlException, message, sql) -> {
            String sqlState = JdbcExceptionHelper.extractSqlState(sqlException);
            if (sqlState == null) {
                return null;
            }
            switch (sqlState) {
                case "40P01": // deadlock detected
                    return new LockAcquisitionException(message, sqlException, sql);
                case "55P03": // lock not available: FOR UPDATE NOWAIT
                    return new PessimisticLockException(message, sqlException, sql);
                case "57014": // statement cancelled by its timeout
                    return new QueryTimeoutException(message, sqlException, sql);
                default:
                    return null;
            }
        };
    }
}
